import com.example.domain.model.WoodTheme

@Immutable
data class WoodPalette(
    val theme: WoodTheme,
    val canvasBgTop: Color,
    val canvasBgBottom: Color,
    val woodGrainStroke: Color,
    val cardSurface: Color,
    val cardSurfaceAlt: Color,
    val cardBorder: Color,
    val cardHighlightTop: Color,
    val cardShadowBottom: Color,
    val boardFrameOuter: Color,
    val boardFrameInner: Color,
    val cellBaseLight: Color,
    val cellBaseWarm: Color,
    val cellGivenTile: Color,
    val cellPeerHighlight: Color,
    val cellSameDigitHighlight: Color,
    val cellSelectedTile: Color,
    val cellErrorTint: Color,
    val gridThinLine: Color,
    val gridJoineryLine: Color,
    val textPrimary: Color,
    val textSecondary: Color,
    val givenDigitColor: Color,
    val playerDigitColor: Color,
    val notesDigitColor: Color,
    val errorDigitColor: Color,
    val accentPrimary: Color,
    val onAccentPrimary: Color,
    val accentBrass: Color,
    val successWoodPine: Color,
    val keypadTileTop: Color,
    val keypadTileBottom: Color,
    val shimmerGold: Color
) {
    fun toMaterialColorScheme(): ColorScheme = if (theme.isDarkSurface) {
        darkColorScheme(
            primary = accentPrimary,
            onPrimary = onAccentPrimary,
            primaryContainer = cardSurfaceAlt,
            onPrimaryContainer = textPrimary,
            secondary = accentBrass,
            onSecondary = onAccentPrimary,
            secondaryContainer = boardFrameInner,
            onSecondaryContainer = textPrimary,
            tertiary = successWoodPine,
            background = canvasBgTop,
            onBackground = textPrimary,
            surface = cardSurface,
            onSurface = textPrimary,
            surfaceVariant = cardSurfaceAlt,
            onSurfaceVariant = textSecondary,
            outline = cardBorder,
            error = errorDigitColor
        )
    } else {
        lightColorScheme(
            primary = accentPrimary,
            onPrimary = onAccentPrimary,
            primaryContainer = cardSurfaceAlt,
            onPrimaryContainer = textPrimary,
            secondary = accentBrass,
            onSecondary = onAccentPrimary,
            secondaryContainer = boardFrameInner,
            onSecondaryContainer = textPrimary,
            tertiary = successWoodPine,
            background = canvasBgTop,
            onBackground = textPrimary,
            surface = cardSurface,
            onSurface = textPrimary,
            surfaceVariant = cardSurfaceAlt,
            onSurfaceVariant = textSecondary,
            outline = cardBorder,
            error = errorDigitColor
        )
    }
}

